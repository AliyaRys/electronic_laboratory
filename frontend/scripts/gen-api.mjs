#!/usr/bin/env node
/**
 * Regenerate src/shared/api/schema.d.ts from the running backend (SPEC-02:
 * «shared/api/schema.d.ts генерируется; предметные DTO вручную не дублируются»).
 *
 * Usage:
 *   1. Serve the backend OpenAPI document, for example:
 *        docker compose -f docker-compose.yml -f docker-compose.dev.yml up -d postgres
 *        DATABASE_URL=... REDIS_URL=... SECRET_KEY=... \
 *          uv run --frozen python -m uvicorn backend.src.interfaces.main:app --port 8000
 *   2. npm run gen:api          # default http://127.0.0.1:8000/openapi.json
 *      BACKEND_URL=... npm run gen:api
 *
 * The backend serves the document at the application root (``/openapi.json``);
 * its paths already contain the full ``/api/v1`` prefix, which is what
 * openapi-fetch with an empty baseUrl expects (ADR-010).
 */

import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { default as openapiTypescript, astToString } from "openapi-typescript";

const backendUrl = process.env.BACKEND_URL ?? "http://127.0.0.1:8000/openapi.json";
const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(here, "..", "src", "shared", "api", "schema.d.ts");

const response = await fetch(backendUrl, { headers: { accept: "application/json" } });
if (!response.ok) {
  console.error(`gen:api: backend answered ${response.status} for ${backendUrl}`);
  process.exit(1);
}
const schema = await response.json();

const contents = astToString(await openapiTypescript(schema, {}));
await writeFile(
  outFile,
  `// Generated by \`npm run gen:api\` from the backend OpenAPI document. DO NOT EDIT.\n${contents}`,
);
console.log(`gen:api: wrote ${path.relative(process.cwd(), outFile)} (${backendUrl})`);
