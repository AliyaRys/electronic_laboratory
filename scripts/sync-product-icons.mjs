/**
 * DR50: single source of truth for the three product-type icons.
 *
 * Reads the pinned ``@fortawesome/free-solid-svg-icons`` package and writes
 * two generated artifacts that are committed:
 *
 *   1. a marked generated block inside ``components/shell/AppHeader.js``
 *      (legacy plain-script registry),
 *   2. ``frontend/src/shared/ui/product-icons.generated.ts`` (React adapter).
 *
 * Hand-written SVG is forbidden for these keys (ТЗ DR50 §2.2); run
 * ``node scripts/sync-product-icons.mjs`` after a deliberate version bump and
 * ``node scripts/sync-product-icons.mjs --check`` in CI/gates — it exits
 * non-zero when a committed artifact diverges from the pinned package.
 *
 * Only three icon definitions are generated: the whole Font Awesome package
 * is never shipped to the runtime bundle.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { faEgg, faFish, faWheatAwn } from "@fortawesome/free-solid-svg-icons";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

/** Application key → Font Awesome export (exact mapping, ТЗ DR50 §2.1). */
const MAPPING = {
  "product-eggs": faEgg,
  "product-fish": faFish,
  "product-plant": faWheatAwn,
};

const FONT_AWESOME_VERSION = "7.3.1";

const collect = () =>
  Object.fromEntries(
    Object.entries(MAPPING).map(([key, icon]) => {
      const [width, height, , , svgPathData] = icon.icon;
      const parts = (Array.isArray(svgPathData) ? svgPathData : [svgPathData]).map((d) => ({
        d,
      }));
      return [
        key,
        {
          source: "font-awesome-free-solid",
          version: FONT_AWESOME_VERSION,
          width,
          height,
          solid: true,
          parts,
        },
      ];
    }),
  );

const data = collect();

// --- artifact 1: generated block in the legacy AppHeader.js registry ---
const HEADER_PATH = join(root, "components", "shell", "AppHeader.js");
const BEGIN = "  // ==== GENERATED: product icons (scripts/sync-product-icons.mjs) — do not edit ====\n";
const END = "  // ==== END GENERATED product icons ====\n";

const renderLegacyBlock = () => {
  const lines = Object.entries(data).map(
    ([key, def]) =>
      `    ${JSON.stringify(key)}: { width: ${def.width}, height: ${def.height}, solid: true, parts: ${JSON.stringify(def.parts)} },`,
  );
  return (
    BEGIN +
    `  const productIcons = {\n` +
    lines.join("\n") +
    `,\n  };\n` +
    END
  );
};

// --- artifact 2: TypeScript data for the React adapter ---
const GENERATED_TS_PATH = join(root, "frontend", "src", "shared", "ui", "product-icons.generated.ts");
const renderTs = () => {
  const lines = Object.entries(data).map(
    ([key, def]) =>
      `  ${JSON.stringify(key)}: Object.freeze({ width: ${def.width}, height: ${def.height}, solid: true, parts: Object.freeze(${JSON.stringify(def.parts)}) }),`,
  );
  return `/**
 * GENERATED by scripts/sync-product-icons.mjs from the pinned
 * Font Awesome Free Solid package (exact version ${FONT_AWESOME_VERSION}).
 * Do not edit by hand: run "node scripts/sync-product-icons.mjs" and
 * commit; "node scripts/sync-product-icons.mjs --check" guards drift.
 */

export interface ProductIconData {
  readonly width: number;
  readonly height: number;
  readonly solid: boolean;
  readonly parts: ReadonlyArray<{ readonly d: string }>;
}

export const PRODUCT_ICON_DATA: Readonly<Record<string, ProductIconData>> = Object.freeze({
${lines.join("\n")},
});
`;
};

const headerSource = readFileSync(HEADER_PATH, "utf8");
const beginIndex = headerSource.indexOf(BEGIN);
const endIndex = headerSource.indexOf(END);
if (beginIndex === -1 || endIndex === -1) {
  console.error("AppHeader.js is missing the generated product-icons block markers.");
  process.exit(1);
}

const legacyBlock = renderLegacyBlock();
const tsSource = renderTs();
const check = process.argv.includes("--check");
if (check) {
  const current = headerSource.slice(beginIndex, endIndex + END.length);
  const committedTs = readFileSync(GENERATED_TS_PATH, "utf8");
  const errors = [];
  if (current !== legacyBlock) errors.push("components/shell/AppHeader.js generated block diverges from the pinned package.");
  if (committedTs !== tsSource) errors.push("frontend/src/shared/ui/product-icons.generated.ts diverges from the pinned package.");
  if (errors.length > 0) {
    errors.forEach((error) => console.error(error));
    console.error("Run \"node scripts/sync-product-icons.mjs\" and commit the result.");
    process.exit(1);
  }
  console.log("Product icon artifacts match the pinned Font Awesome package.");
} else {
  const next =
    headerSource.slice(0, beginIndex) + legacyBlock + headerSource.slice(endIndex + END.length);
  writeFileSync(HEADER_PATH, next);
  writeFileSync(GENERATED_TS_PATH, tsSource);
  console.log("Product icon artifacts regenerated.");
}
